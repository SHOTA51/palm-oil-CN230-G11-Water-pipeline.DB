"""Generate db/seed.sql from the CSV snapshot in db/csv/.

The CSVs are the export from SHOTA51/palm-oil-CN230-G11-Water-pipeline.DB
(DATA_SET/export_csv). They already carry primary keys, so foreign keys stay
intact. Empty CSV cells become NULL.

    python db/build_seed.py
"""
from __future__ import annotations

import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
CSV_DIR = HERE / "csv"
OUT = HERE / "seed.sql"

# Parents before children so every foreign key resolves on insert.
TABLES = [
    ("locations", ["location_id", "name_th", "name_en", "level", "parent_id"]),
    ("commodities", ["commodity_id", "commodity_name", "subcom_name"]),
    ("units", ["unit_id", "unit_name"]),
    ("items", ["item_id", "item_name", "unit_id"]),
    ("data_releases", ["release_id", "data_date", "data_date_th"]),
    ("production_stats", ["stat_id", "location_id", "commodity_id", "item_id", "release_id", "year", "crop_year", "value"]),
]
NUMERIC = {"location_id", "parent_id", "commodity_id", "unit_id", "item_id", "release_id", "stat_id", "year", "crop_year", "value"}
BATCH = 500


def literal(col: str, raw: str) -> str:
    if raw == "":
        return "NULL"
    if col in NUMERIC:
        float(raw)  # fail loudly on anything that is not a number
        return raw
    return "'" + raw.replace("\\", "\\\\").replace("'", "''") + "'"


def main() -> None:
    out = [
        "-- Generated by db/build_seed.py from db/csv/*.csv. Do not edit by hand.",
        "SET NAMES utf8mb4;",
        "USE `plam-oil`;",
        "",
    ]
    for table, cols in TABLES:
        with open(CSV_DIR / f"{table}.csv", encoding="utf-8-sig", newline="") as fh:
            rows = list(csv.DictReader(fh))
        out.append(f"-- {table}: {len(rows)} rows")
        for i in range(0, len(rows), BATCH):
            values = ",\n".join("(" + ", ".join(literal(c, r[c]) for c in cols) + ")" for r in rows[i : i + BATCH])
            out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{values};")
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
